"""initial base schema

Revision ID: 0001
Revises:
Create Date: 2026-08-13

Creates the whole ``base`` schema in a single revision: the schema itself, the
two named native enum types, the shared ``base.set_updated_at()`` trigger
function, the twenty tables of SPEC-001 section 6.1 with their constraints and
timestamp columns, one ``updated_at`` trigger per table, and a ``COMMENT ON``
for every object class. ``downgrade`` is the exact mirror and leaves no residue:
it ends with an unconditional ``DROP SCHEMA base RESTRICT``. That is only safe
because ``migrations/env.py`` keeps alembic's version table out of ``base``, so
every object in the schema is owned by this revision.

Every raw-SQL string is schema qualified so that the migration never depends on
``search_path``. No secondary indexes are created: uniqueness is expressed only
through unique constraints, whose backing indexes are implicit.
"""

