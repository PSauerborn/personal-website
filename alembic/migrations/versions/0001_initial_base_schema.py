def upgrade() -> None:
    """upgrade applies the schema changes of this revision.

    Objects are emitted in strict dependency order: the schema, both enum
    types and the trigger function first, then the twenty tables parents
    before children, then one updated_at trigger per table. Each enum type is
    commented immediately after it is created; the comment lives and dies with
    the type, so :func:`downgrade` has no counterpart to emit.

    Returns:
        None.
    """

    create_schema()

    bind = op.get_bind()
    HTTP_METHOD.create(bind, checkfirst=False)
    execute_sql(f"""
        COMMENT ON TYPE {SCHEMA}.http_method IS
            'HTTP method of the request recorded on an admin audit-log entry.';
        """)

    DOCUMENT_TYPE.create(bind, checkfirst=False)
    execute_sql(f"""
        COMMENT ON TYPE {SCHEMA}.document_type IS
            'Role a linked document plays for an agent spec.';
        """)

    create_set_updated_at_function()

    for table in TABLES:
        TABLE_BUILDERS[table]()

    for table in TABLES:
        create_updated_at_trigger(table)


def downgrade() -> None:
    """downgrade reverts the schema changes of this revision.

    The mirror of :func:`upgrade`: triggers, then tables in reverse dependency
    order, then the trigger function, both enum types and finally the schema
    itself.

    Returns:
        None.
    """

    for table in reversed(TABLES):
        drop_updated_at_trigger(table)

    for table in reversed(TABLES):
        op.drop_table(table, schema=SCHEMA)

    drop_set_updated_at_function()

    bind = op.get_bind()
    DOCUMENT_TYPE.drop(bind, checkfirst=False)
    HTTP_METHOD.drop(bind, checkfirst=False)

    drop_schema()
