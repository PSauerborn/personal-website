def execute_sql(statement: str) -> None:
    """execute_sql emits a raw SQL statement with consistent formatting.

    The statement is dedented and stripped of its trailing semicolon, since
    alembic terminates every statement it emits itself.

    Args:
        statement: Raw, schema-qualified SQL statement.

    Returns:
        None.
    """

    op.execute(textwrap.dedent(statement).strip().rstrip(";"))


def id_column() -> sa.Column:
    """id_column builds the primary-key column shared by every table.

    Returns:
        sa.Column: A ``VARCHAR(32)`` primary-key column holding a hyphen-free
        UUIDv7 hex string generated by the application.
    """

    return sa.Column(
        "id",
        sa.String(length=ID_LENGTH),
        nullable=False,
        comment=(
            "Primary key. UUIDv7 rendered as hex with hyphens removed, "
            "generated by the application."
        ),
    )


def fk_column(name: str, description: str, nullable: bool = False) -> sa.Column:
    """fk_column builds a foreign-key column matching the primary-key width.

    Args:
        name: Name of the column.
        description: Text used as the column comment.
        nullable: Whether the column accepts NULL values.

    Returns:
        sa.Column: A ``VARCHAR(32)`` column referencing another table's primary
        key.
    """

    return sa.Column(
        name,
        sa.String(length=ID_LENGTH),
        nullable=nullable,
        comment=description,
    )


def timestamp_columns() -> list[sa.Column]:
    """timestamp_columns builds the created_at and updated_at columns.

    Both columns are timezone aware and defaulted server side with ``now()``;
    ``updated_at`` is additionally maintained by the per-table trigger created
    in :func:`create_updated_at_trigger`.

    Returns:
        list[sa.Column]: Freshly constructed ``created_at`` and ``updated_at``
        columns, safe to attach to a single table.
    """

    return [
        sa.Column(
            "created_at",
            sa.TIMESTAMP(timezone=True),
            nullable=False,
            server_default=sa.func.now(),
            comment=(
                "UTC timestamp of row creation. Set by the server default; "
                "never supplied by callers."
            ),
        ),
        sa.Column(
            "updated_at",
            sa.TIMESTAMP(timezone=True),
            nullable=False,
            server_default=sa.func.now(),
            comment=(
                "UTC timestamp of the last update. Maintained by the "
                "table's set_updated_at trigger."
            ),
        ),
    ]


def create_updated_at_trigger(table: str) -> None:
    """create_updated_at_trigger attaches the shared trigger to one table.

    Args:
        table: Unqualified name of the table in the ``base`` schema.

    Returns:
        None.
    """

    execute_sql(f"""
        CREATE TRIGGER {table}_set_updated_at
            BEFORE UPDATE ON {SCHEMA}.{table}
            FOR EACH ROW
            EXECUTE FUNCTION {SCHEMA}.set_updated_at();
        """)
    execute_sql(f"""
        COMMENT ON TRIGGER {table}_set_updated_at ON {SCHEMA}.{table} IS
            'Keeps {SCHEMA}.{table}.updated_at current on every UPDATE.';
        """)


def drop_updated_at_trigger(table: str) -> None:
    """drop_updated_at_trigger removes the updated_at trigger from one table.

    Args:
        table: Unqualified name of the table in the ``base`` schema.

    Returns:
        None.
    """

    execute_sql(f"DROP TRIGGER {table}_set_updated_at ON {SCHEMA}.{table};")


def create_schema() -> None:
    """create_schema creates the base schema and comments it.

    ``IF NOT EXISTS`` is retained purely so that this revision body can be
    re-run against a database where it has already been applied; no other
    component creates ``base`` beforehand. In particular alembic's own version
    table is *not* placed here - ``migrations/env.py`` configures no
    ``version_table_schema`` - so on a fresh database this statement is what
    brings the schema into existence, and everything in it is owned by this
    revision.

    Returns:
        None.
    """

    execute_sql(f"CREATE SCHEMA IF NOT EXISTS {SCHEMA};")
    execute_sql(f"""
        COMMENT ON SCHEMA {SCHEMA} IS
            'Application schema holding every entity of the website backend.';
        """)


def drop_schema() -> None:
    """drop_schema removes the base schema once its objects are gone.

    The drop is unconditional and is the exact mirror of the schema creation in
    :func:`create_schema`. ``RESTRICT`` is deliberate: every object owned by this
    revision has been dropped explicitly by the time this runs, so the statement
    can only fail if something the revision does not own was created inside the
    schema - which must fail loudly rather than be dropped silently. Nothing
    else lives here: alembic's version table is kept outside this schema by
    ``migrations/env.py`` precisely so that this drop can be unconditional.

    Returns:
        None.
    """

    execute_sql(f"DROP SCHEMA {SCHEMA} RESTRICT;")


def create_set_updated_at_function() -> None:
    """create_set_updated_at_function creates the shared trigger function.

    One function is defined per schema and attached to every table by
    :func:`create_updated_at_trigger`.

    Returns:
        None.
    """

    execute_sql(f"""
        CREATE FUNCTION {SCHEMA}.set_updated_at()
        RETURNS trigger AS $$
        BEGIN
            NEW.updated_at = now();
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql;
        """)
    execute_sql(f"""
        COMMENT ON FUNCTION {SCHEMA}.set_updated_at() IS
            'Trigger function that stamps updated_at with the current UTC'
            ' time on every UPDATE.';
        """)


def drop_set_updated_at_function() -> None:
    """drop_set_updated_at_function removes the shared trigger function.

    Returns:
        None.
    """

    execute_sql(f"DROP FUNCTION {SCHEMA}.set_updated_at();")


